 function [7:0] ms11_to_bcd;
  input [10:0] ms_in;
  reg [11:0] qr0;
  reg [5:0]  rsum;
  reg        ge50, ge25;
  reg [1:0]  inc;
  reg [6:0]  q25;
  reg [7:0]  ms_bcd;
  begin
   qr0    = ms_hi_div25(ms_in[10:5]);
   rsum   = {1'b0, qr0[4:0]} + {1'b0, ms_in[4:0]};
   ge50   = (rsum[5:4] == 2'b11) && (rsum[3] || rsum[2] || rsum[1]);
   ge25   = rsum[5] || (rsum[4] && rsum[3] && (|rsum[2:0]));
   inc    = ge50 ? 2'd2 : ge25 ? 2'd1 : 2'd0;
   q25    = qr0[11:5] + {5'd0, inc};
   ms_bcd = bcd7_hi(q25[6:1]);
   ms11_to_bcd = {ms_bcd[6:3], ms_bcd[2:0], q25[0]};
  end
 endfunction

