    if(plot_h == 7'd60 && !pixel_x[3]) pal_code = 4'd6;
    if(read_class != 2'd3 && (plot_h == read_height || (read_height != 7'd0 && plot_h == (read_height - 7'd1)))) begin
     case(read_class)
      2'd0: pal_code = 4'd2;
      2'd1: pal_code = 4'd3;
      2'd2: pal_code = 4'd4;
      default: begin end
     endcase
    end
   end
   if((x_in_640 && (pixel_x[9:1] == 9'd47) && y_in_512 && (line_y >= 12'd224 && line_y < 12'd347)) ||
      (x_in_640 && (pixel_x >= 12'd94 && pixel_x < 12'd498) && y_in_512 && (line_y[8:1] == 8'd172 && line_y[0] || line_y[8:0] == 9'd346)))
    pal_code = 4'd1;
  end
  if(text_cell) pal_code = tc_pal;
 end

 always @(posedge clk or negedge rst_n) begin
  if(!rst_n) begin
   pipe_bit<=0;pipe_text<=0;pipe_valid<=0;pipe_pal<=0;pipe_background<=0;
  end else begin
   pipe_bit<=text_bit;
   pipe_text<=text_cell;
   pipe_valid<=enable && frame_enable && de;
   pipe_pal<=pal_code;
   pipe_background<=rgb_in;
  end
 end

