`ifdef SIMULATION
    // Behavioural model (the TD BRAM32K simulation model is encrypted).
    reg [15:0] mem [0:SUB_NBLK*2048-1];
    reg [15:0] q, qb;
    initial $readmemh("subtitle_rom.hex", mem);
    always @(posedge clk) begin
        q  <= mem[addr];
        qb <= mem[(SUB_NBLK-1)*2048 + addrb];
    end
    assign dout = q;
    assign doutb = qb;
`else
