    reg [4:0] convert_count;
    reg converting;

    function [3:0] dabble_nib;
        input [3:0] d;
        begin
            case(d)
                4'd0: dabble_nib = 4'd0;
                4'd1: dabble_nib = 4'd1;
                4'd2: dabble_nib = 4'd2;
                4'd3: dabble_nib = 4'd3;
                4'd4: dabble_nib = 4'd4;
                4'd5: dabble_nib = 4'd8;
                4'd6: dabble_nib = 4'd9;
                4'd7: dabble_nib = 4'd10;
                4'd8: dabble_nib = 4'd11;
                4'd9: dabble_nib = 4'd12;
                default: dabble_nib = d;
            endcase
        end
    endfunction

    function [18:0] decimal_adjust;
        input [19:0] value;
        begin
            // For 16-bit unsigned input, value[19:16] never reaches >= 5 before any shift.
            decimal_adjust = {
                value[18:16],
                dabble_nib(value[15:12]),
                dabble_nib(value[11:8]),
                dabble_nib(value[7:4]),
                dabble_nib(value[3:0])
            };
        end
    endfunction

    wire [18:0] next_noise = decimal_adjust(noise_bcd);
    wire [18:0] next_voice = decimal_adjust(voice_bcd);
    wire [18:0] next_threshold = decimal_adjust(threshold_bcd);

    always @(posedge clk or negedge rst_n) begin
        if(!rst_n) begin
            pixel_x<=0;line_y<=0;de_q<=0;vs_q<=1;
            frame_status<=0;frame_brightness<=8;frame_mode<=0;frame_select<=0;
            noise_shift<=0;voice_shift<=0;threshold_shift<=0;
            noise_bcd<=0;voice_bcd<=0;threshold_bcd<=0;
            convert_count<=0;converting<=0;
        end else begin
            de_q<=de;vs_q<=vsync;
            if(!vsync || !de)pixel_x<=0;else pixel_x<=pixel_x+1'b1;
            if(!vsync)line_y<=0;else if(de_q && !de)line_y<=line_y+1'b1;
            if(vs_q && !vsync) begin
                frame_status<=status;frame_brightness<=brightness;
                frame_mode<=mode;frame_select<=select_threshold;
                noise_shift<=noise_floor;voice_shift<=voice_reference;
                threshold_shift<=loud_threshold;
                noise_bcd<=0;voice_bcd<=0;threshold_bcd<=0;
                convert_count<=0;converting<=1;
            end else if(converting) begin
                noise_bcd<={next_noise,noise_shift[15]};
                voice_bcd<={next_voice,voice_shift[15]};
                threshold_bcd<={next_threshold,threshold_shift[15]};
                noise_shift<={noise_shift[14:0],1'b0};
                voice_shift<={voice_shift[14:0],1'b0};
                threshold_shift<={threshold_shift[14:0],1'b0};
                if(convert_count==15)converting<=0;
                else convert_count<=convert_count+1'b1;
            end
        end
    end

