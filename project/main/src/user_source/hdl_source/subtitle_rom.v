// Subtitle ROM: SUB_NBLK x EG_PHY_BRAM32K (DP16K, 2048 x 16, NOREG).
// Port A (all blocks): addr = global word address (block addr[14:11], word addr[10:0]),
//   dout = word at addr one clock later (synchronous BRAM read; the block select is
//   registered with the address, the 16-bit block mux after the BRAMs is combinational).
// Port B (last block only): addrb = word address inside block SUB_NBLK-1, doutb one
//   clock later; used for the per-sentence meta words.
// Contents: subtitle_rom_init.vh (synthesis; SUB_INIT_Bn, INIT_xx bit[16j+15:16j] =
// word xx*16+j of block n) / subtitle_rom.hex (SIMULATION, one 16-bit word per line,
// read from the simulator working directory). Both are generated by
// an offline Python generator (not included), which also cross-checks the two.
// Word format: 4 pixels of one sentence row, pixel c%4 = j in bit[4j+3:4j],
// pixel = {o[1:0], f[1:0]} (outline alpha, fill alpha).
module subtitle_rom (
    input  wire        clk,
    input  wire [14:0] addr,
    output wire [15:0] dout,
    input  wire [10:0] addrb,
    output wire [15:0] doutb
